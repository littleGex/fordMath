import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import type { Plugin } from "vite";

/** Files that must never be stored: the service worker itself and GitHub Pages' marker. */
const SKIP = new Set(["sw.js", ".nojekyll"]);

/**
 * Turns built file paths into the URLs the browser will ask for.
 * "index.html" → "/fordMath/", "stats/index.html" → "/fordMath/stats/", others keep their path.
 */
export function precacheUrls(files: readonly string[], base: string): string[] {
  return files
    .filter((f) => !SKIP.has(f))
    .map((f) => (f === "index.html" ? base : f.endsWith("/index.html") ? base + f.slice(0, -"index.html".length) : base + f))
    .sort();
}

/** A short hash of every file's path and content: it changes whenever anything in the build does. */
export function versionOf(files: ReadonlyArray<{ path: string; content: Buffer | string }>): string {
  const hash = createHash("sha256");
  for (const f of [...files].sort((a, b) => a.path.localeCompare(b.path))) {
    if (SKIP.has(f.path)) continue;
    hash.update(f.path).update("\0").update(f.content).update("\0");
  }
  return hash.digest("hex").slice(0, 12);
}

/** The finished service worker: the three constants, then the template. */
export function swSource(template: string, base: string, version: string, urls: readonly string[]): string {
  return [
    "// Generated by build/sw-plugin.ts. Edit build/sw-template.js instead.",
    `const BASE = ${JSON.stringify(base)};`,
    `const VERSION = ${JSON.stringify(version)};`,
    `const PRECACHE = ${JSON.stringify(urls, null, 2)};`,
    "",
    template,
  ].join("\n");
}

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? listFiles(full) : [full];
  });
}

/** Vite plugin: after the build is written, adds dist/sw.js listing every file in dist. */
export function serviceWorker(templatePath: string): Plugin {
  let outDir = "dist";
  let base = "/";
  return {
    name: "fordmath-service-worker",
    apply: "build",
    configResolved(config) {
      outDir = config.build.outDir;
      base = config.base;
    },
    closeBundle() {
      const files = listFiles(outDir).map((full) => ({
        path: relative(outDir, full).split(sep).join("/"),
        content: readFileSync(full),
      }));
      const urls = precacheUrls(files.map((f) => f.path), base);
      const code = swSource(readFileSync(templatePath, "utf8"), base, versionOf(files), urls);
      writeFileSync(join(outDir, "sw.js"), code);
      this.info?.(`service worker: ${urls.length} files stored for offline use`);
    },
  };
}
